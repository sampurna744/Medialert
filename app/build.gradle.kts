// Read API key from local.properties — no import needed
val groqApiKey: String = run {
    val propsFile = rootProject.file("local.properties")
    if (propsFile.exists()) {
        propsFile.readLines()
            .firstOrNull { it.startsWith("groq.api_key=") }
            ?.removePrefix("groq.api_key=")
            ?.trim()
            ?: ""
    } else ""
}

